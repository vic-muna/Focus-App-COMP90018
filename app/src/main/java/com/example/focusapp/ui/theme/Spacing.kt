package com.example.focusapp.ui.theme

import androidx.compose.ui.unit.dp

/**
 * App-wide layout gaps. Both are measured inside the system bars (status
 * bar on top, gesture/navigation bar at the bottom), not from the physical
 * screen edge.
 */
object FocusSpacing {
    /** From the top of the screen content to top-pinned items (e.g. the settings gear). */
    val ScreenTop = 40.dp

    /** From the bottom of the screen content to bottom-pinned items (nav bar, fly cards, buttons). */
    val ScreenBottom = 40.dp
}
